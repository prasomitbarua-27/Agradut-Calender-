#!/usr/bin/env python3
"""
Reads the Kathin Chibar Dan 2026 workbook and writes:
  src/data/viharas.ts   (one record per unique Vihara name)
  src/data/events.ts    (one record per schedule row)

Nothing is invented: names, dates and districts are copied from the workbook.
Run:  python3 scripts/import_schedule.py path/to/workbook.xlsx
Needs: pip install openpyxl
"""
import sys, json, unicodedata, datetime, collections
import openpyxl

SRC = sys.argv[1] if len(sys.argv) > 1 else "kathin_chibar_dan_2026_districts_draft.xlsx"
OUT = "src/data/"

BN = str.maketrans("০১২৩৪৫৬৭৮৯", "0123456789")
MONTHS = {"জানুয়ারি":1,"ফেব্রুয়ারি":2,"মার্চ":3,"এপ্রিল":4,"মে":5,"জুন":6,
          "জুলাই":7,"আগস্ট":8,"সেপ্টেম্বর":9,"অক্টোবর":10,"নভেম্বর":11,"ডিসেম্বর":12}
# Python weekday(): Monday=0
WEEKDAYS = {"সোমবার":0,"মঙ্গলবার":1,"বুধবার":2,"বৃহস্পতিবার":3,"শুক্রবার":4,"শনিবার":5,"রবিবার":6}

ABROAD = "বাংলাদেশের জেলা নয়—বিদেশে"
UNKNOWN = "যাচাই প্রয়োজন"

def clean(s):
    return unicodedata.normalize("NFC", str(s)).strip()

def parse_date(text):
    day, month, year = clean(text).split()
    return datetime.date(int(year.translate(BN)), MONTHS[month], int(day.translate(BN)))

def status_of(district, basis_note):
    if district == UNKNOWN: return "unverified"
    if district == ABROAD: return "abroad"
    if "স্পষ্ট" in basis_note: return "explicit"
    return "inferred"

wb = openpyxl.load_workbook(SRC, read_only=True)
ws = wb.worksheets[0]
rows = [r for r in ws.iter_rows(min_row=2, values_only=True) if any(r)]

viharas = collections.OrderedDict()   # name -> record
events = []
problems = []
for serial, dtext, wd, _dayno, name, district, basis, verify in rows:
    name, district, basis, verify = map(clean, (name, district, basis, verify))
    d = parse_date(dtext)
    if d.weekday() != WEEKDAYS[clean(wd)]:
        problems.append(f"row {serial}: weekday mismatch {dtext} / {wd}")
    if name not in viharas:
        viharas[name] = {"id": f"vihara-{len(viharas)+1:03d}", "name": name,
                         "district": district, "districtStatus": status_of(district, verify),
                         "districtBasis": basis}
    else:
        v = viharas[name]
        if v["district"] != district:
            problems.append(f"row {serial}: district differs for same name {name}")
    events.append({"id": f"event-{int(serial):04d}", "serial": int(serial),
                   "date": d.isoformat(), "viharaId": viharas[name]["id"]})

if problems:
    print("PROBLEMS:"); [print(" ", p) for p in problems]; sys.exit(1)

def ts(obj):  # JSON is valid TypeScript for plain objects
    return json.dumps(obj, ensure_ascii=False)

hdr_v = '''import type { Vihara } from "@/types";

/**
 * GENERATED by scripts/import_schedule.py from the 2026 workbook. Do not edit by hand.
 * Districts are a DRAFT: only "explicit" ones are written plainly in the Vihara name.
 * "inferred" = guessed from a place name; "unverified" = unknown; "abroad" = outside Bangladesh.
 * Latitude, longitude, address and contact are left out on purpose: the workbook has none.
 */
export const viharas: Vihara[] = [
'''
with open(OUT + "viharas.ts", "w", encoding="utf-8") as f:
    f.write(hdr_v)
    for v in viharas.values(): f.write("  " + ts(v) + ",\n")
    f.write("];\n")

hdr_e = '''import type { KathinEvent } from "@/types";

/**
 * GENERATED by scripts/import_schedule.py from the 2026 workbook. Do not edit by hand.
 * One record per schedule row (`serial` = the row number in the workbook).
 * Source of the schedule, as named in the workbook: tathagata.online, 2026 Kathin Chibar Dan list.
 */
const TITLE = "কঠিন চীবরদান";

export const events: KathinEvent[] = [
'''
with open(OUT + "events.ts", "w", encoding="utf-8") as f:
    f.write(hdr_e)
    for e in events:
        f.write("  { id: %s, serial: %d, title: TITLE, date: %s, viharaId: %s },\n"
                % (json.dumps(e["id"]), e["serial"], json.dumps(e["date"]), json.dumps(e["viharaId"])))
    f.write("];\n")

c = collections.Counter(v["districtStatus"] for v in viharas.values())
print(f"events written: {len(events)}  viharas written: {len(viharas)}  vihara status: {dict(c)}")
